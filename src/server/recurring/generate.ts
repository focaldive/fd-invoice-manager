import "server-only";
import { db } from "@/server/db/client";
import {
  invoices,
  invoiceItems,
  payslips,
  payslipItems,
  recurringInvoices,
  recurringInvoiceItems,
  recurringPayslips,
  recurringPayslipItems,
  clients,
  employees,
} from "@/server/db/schema";
import { and, asc, eq, lte } from "drizzle-orm";
import { revalidatePath } from "next/cache";
import { nextInvoiceNumber } from "@/server/invoice-numbering";
import { nextSlipNumber } from "@/server/payslip-numbering";
import {
  addDaysToDateString,
  computeNetPay,
  dayInMonthAfter,
  parseDateString,
  shiftMonth,
  toDateString,
} from "@/lib/types";

/**
 * Safety cap: how many missed months one template may catch up in a single
 * run (e.g. after the server was down). Anything beyond is picked up next run.
 */
const MAX_CATCH_UP = 12;

export type RecurringRunResult = {
  invoices: { templateId: string; id: string; number: string }[];
  payslips: { templateId: string; id: string; number: string }[];
  skipped: { templateId: string; kind: "invoice" | "payslip"; reason: string }[];
  errors: { templateId: string; kind: "invoice" | "payslip"; message: string }[];
};

const round2 = (n: number) => Math.round(n * 100) / 100;

/**
 * Generate one invoice per due run date for a recurring invoice template.
 * The template row is locked FOR UPDATE, so concurrent runs can never
 * produce the same month twice.
 */
async function runInvoiceTemplate(templateId: string, today: string, result: RecurringRunResult) {
  await db.transaction(async (tx) => {
    const [template] = await tx
      .select()
      .from(recurringInvoices)
      .where(eq(recurringInvoices.id, templateId))
      .for("update");
    if (!template || !template.isActive || template.nextGenerationDate > today) return;

    const [client] = await tx.select().from(clients).where(eq(clients.id, template.clientId));
    if (!client) {
      result.skipped.push({ templateId, kind: "invoice", reason: "Client no longer exists" });
      return;
    }

    const items = await tx
      .select()
      .from(recurringInvoiceItems)
      .where(eq(recurringInvoiceItems.recurringInvoiceId, templateId))
      .orderBy(asc(recurringInvoiceItems.sortOrder));

    // Same maths as the invoice form: tax and discount both apply to the subtotal.
    const subtotal = round2(items.reduce((s, i) => s + Number(i.quantity) * Number(i.unitPrice), 0));
    const taxPercentage = Number(template.taxPercentage);
    const discountPercentage = Number(template.discountPercentage);
    const taxAmount = round2(subtotal * (taxPercentage / 100));
    const discountAmount =
      discountPercentage > 0
        ? round2(subtotal * (discountPercentage / 100))
        : Number(template.discountAmount);
    const total = round2(subtotal + taxAmount - discountAmount);

    let runDate = template.nextGenerationDate;
    let generated = 0;
    while (runDate <= today && generated < MAX_CATCH_UP) {
      const invoiceNumber = await nextInvoiceNumber(client.name, parseDateString(runDate), tx);
      const [row] = await tx
        .insert(invoices)
        .values({
          invoiceNumber,
          clientId: template.clientId,
          dateOfIssue: runDate,
          dateDue: addDaysToDateString(runDate, template.paymentTermsDays),
          status: "draft",
          subtotal: String(subtotal),
          taxPercentage: template.taxPercentage,
          taxAmount: String(taxAmount),
          discountPercentage: template.discountPercentage,
          discountAmount: String(discountAmount),
          total: String(total),
          currency: template.currency,
          notes: template.notes,
          category: template.category,
          recurringInvoiceId: template.id,
          isAutoGenerated: true,
        })
        .returning({ id: invoices.id });

      if (items.length > 0) {
        await tx.insert(invoiceItems).values(
          items.map((it) => ({
            invoiceId: row.id,
            description: it.description,
            quantity: it.quantity,
            unitPrice: it.unitPrice,
            amount: String(round2(Number(it.quantity) * Number(it.unitPrice))),
            sortOrder: it.sortOrder,
          })),
        );
      }

      result.invoices.push({ templateId, id: row.id, number: invoiceNumber });
      generated++;
      runDate = dayInMonthAfter(runDate, template.dayOfMonth);
    }

    await tx
      .update(recurringInvoices)
      .set({
        nextGenerationDate: runDate,
        generatedCount: template.generatedCount + generated,
        lastGeneratedAt: new Date(),
        updatedAt: new Date(),
      })
      .where(eq(recurringInvoices.id, templateId));
  });
}

/** Same as runInvoiceTemplate, for payslips. Inactive employees are skipped. */
async function runPayslipTemplate(templateId: string, today: string, result: RecurringRunResult) {
  await db.transaction(async (tx) => {
    const [template] = await tx
      .select()
      .from(recurringPayslips)
      .where(eq(recurringPayslips.id, templateId))
      .for("update");
    if (!template || !template.isActive || template.nextGenerationDate > today) return;

    const [employee] = await tx.select().from(employees).where(eq(employees.id, template.employeeId));
    if (!employee) {
      result.skipped.push({ templateId, kind: "payslip", reason: "Employee no longer exists" });
      return;
    }
    if (employee.status !== "active") {
      // Don't pay inactive staff. The date stays put, so generation resumes
      // (catching up at most MAX_CATCH_UP months) if they're reactivated.
      result.skipped.push({ templateId, kind: "payslip", reason: `${employee.name} is inactive` });
      return;
    }

    const items = await tx
      .select()
      .from(recurringPayslipItems)
      .where(eq(recurringPayslipItems.recurringPayslipId, templateId))
      .orderBy(asc(recurringPayslipItems.sortOrder));
    const totals = computeNetPay(items.map((i) => ({ type: i.type, amount: Number(i.amount) })));

    let runDate = template.nextGenerationDate;
    let generated = 0;
    while (runDate <= today && generated < MAX_CATCH_UP) {
      const payDate = parseDateString(runDate);
      const period = shiftMonth(payDate.getMonth() + 1, payDate.getFullYear(), template.periodOffsetMonths);
      const slipNumber = await nextSlipNumber(payDate, tx);

      const [row] = await tx
        .insert(payslips)
        .values({
          slipNumber,
          employeeId: template.employeeId,
          payPeriodMonth: period.month,
          payPeriodYear: period.year,
          paymentDate: runDate,
          paymentMode: template.paymentMode,
          status: "draft",
          currency: template.currency,
          grossPay: String(round2(totals.grossPay)),
          totalDeductions: String(round2(totals.totalDeductions)),
          netPay: String(round2(totals.netPay)),
          notes: template.notes,
          authorizedByName: template.authorizedByName,
          authorizedByTitle: template.authorizedByTitle,
          recurringPayslipId: template.id,
          isAutoGenerated: true,
        })
        .returning({ id: payslips.id });

      if (items.length > 0) {
        await tx.insert(payslipItems).values(
          items.map((it) => ({
            payslipId: row.id,
            description: it.description,
            type: it.type,
            amount: it.amount,
            sortOrder: it.sortOrder,
          })),
        );
      }

      result.payslips.push({ templateId, id: row.id, number: slipNumber });
      generated++;
      runDate = dayInMonthAfter(runDate, template.dayOfMonth);
    }

    await tx
      .update(recurringPayslips)
      .set({
        nextGenerationDate: runDate,
        generatedCount: template.generatedCount + generated,
        lastGeneratedAt: new Date(),
        updatedAt: new Date(),
      })
      .where(eq(recurringPayslips.id, templateId));
  });
}

let inFlight: Promise<RecurringRunResult> | null = null;

/**
 * Generate every invoice and payslip whose template is due (next run date on
 * or before today). Idempotent and safe to call as often as you like: each
 * template fires once per month, and the row lock stops concurrent runs from
 * double-generating.
 *
 * Pass `templateId` to limit the run to a single template.
 */
export function runDueRecurring(opts: { today?: string; templateId?: string } = {}) {
  const shared = !opts.templateId && !opts.today;
  if (shared && inFlight) return inFlight;
  const p = doRun(opts).finally(() => {
    if (inFlight === p) inFlight = null;
  });
  if (shared) inFlight = p;
  return p;
}

async function doRun({
  today = toDateString(new Date()),
  templateId,
}: {
  today?: string;
  templateId?: string;
}) {
  const result: RecurringRunResult = { invoices: [], payslips: [], skipped: [], errors: [] };

  const [dueInvoices, duePayslips] = await Promise.all([
    db
      .select({ id: recurringInvoices.id })
      .from(recurringInvoices)
      .where(
        and(
          eq(recurringInvoices.isActive, true),
          lte(recurringInvoices.nextGenerationDate, today),
          templateId ? eq(recurringInvoices.id, templateId) : undefined,
        ),
      ),
    db
      .select({ id: recurringPayslips.id })
      .from(recurringPayslips)
      .where(
        and(
          eq(recurringPayslips.isActive, true),
          lte(recurringPayslips.nextGenerationDate, today),
          templateId ? eq(recurringPayslips.id, templateId) : undefined,
        ),
      ),
  ]);

  // One transaction per template: a failure in one never blocks the others.
  for (const { id } of dueInvoices) {
    try {
      await runInvoiceTemplate(id, today, result);
    } catch (err) {
      result.errors.push({ templateId: id, kind: "invoice", message: errorMessage(err) });
    }
  }
  for (const { id } of duePayslips) {
    try {
      await runPayslipTemplate(id, today, result);
    } catch (err) {
      result.errors.push({ templateId: id, kind: "payslip", message: errorMessage(err) });
    }
  }

  if (result.invoices.length > 0 || result.payslips.length > 0) {
    console.log(
      `[recurring] generated ${result.invoices.length} invoice(s), ${result.payslips.length} payslip(s)`,
    );
    safeRevalidate(["/", "/invoices", "/payslips", "/recurring"]);
  }
  for (const e of result.errors) {
    console.error(`[recurring] ${e.kind} template ${e.templateId} failed: ${e.message}`);
  }
  return result;
}

function errorMessage(err: unknown) {
  return err instanceof Error ? err.message : String(err);
}

/** revalidatePath throws outside a request scope (e.g. the background scheduler). */
function safeRevalidate(paths: string[]) {
  for (const p of paths) {
    try {
      revalidatePath(p);
    } catch {
      // Not in a request — pages read fresh data on their next render anyway.
    }
  }
}
