"use server";

import { db } from "@/server/db/client";
import {
  recurringInvoices,
  recurringInvoiceItems,
  recurringPayslips,
  recurringPayslipItems,
  invoices,
  payslips,
} from "@/server/db/schema";
import { eq } from "drizzle-orm";
import { revalidatePath } from "next/cache";
import { z } from "zod";
import {
  computeNextGenerationDate,
  daysBetweenDateStrings,
  parseDateString,
  toDateString,
} from "@/lib/types";
import { requireSession } from "@/server/auth/session";
import { runDueRecurring } from "@/server/recurring/generate";

const DayOfMonth = z.number().int().min(1).max(28);
const Kind = z.enum(["invoice", "payslip"]);
export type RecurringKind = z.infer<typeof Kind>;

/**
 * Turn a saved invoice into a monthly recurring template. Line items, tax,
 * discount, notes and payment terms are copied from the invoice; the first
 * generated invoice is issued on `dayOfMonth` of the month after it.
 */
export async function makeInvoiceRecurring(invoiceId: string, dayOfMonth: number) {
  await requireSession();
  z.string().uuid().parse(invoiceId);
  DayOfMonth.parse(dayOfMonth);

  const source = await db.query.invoices.findFirst({
    where: (i, { eq }) => eq(i.id, invoiceId),
    with: { items: { orderBy: (it, { asc }) => asc(it.sortOrder) } },
  });
  if (!source) throw new Error("Invoice not found");
  if (!source.clientId) throw new Error("Invoice has no client");
  if (source.recurringInvoiceId) throw new Error("This invoice is already part of a recurring schedule");

  const discountPercentage = Number(source.discountPercentage);

  const row = await db.transaction(async (tx) => {
    const [row] = await tx
      .insert(recurringInvoices)
      .values({
        clientId: source.clientId!,
        currency: source.currency,
        taxPercentage: source.taxPercentage,
        discountPercentage: source.discountPercentage,
        // Percentage discounts are recomputed per run; fixed ones are copied as-is.
        discountAmount: discountPercentage > 0 ? "0" : source.discountAmount,
        notes: source.notes,
        category: source.category,
        paymentTermsDays: Math.max(0, daysBetweenDateStrings(source.dateOfIssue, source.dateDue)),
        dayOfMonth,
        isActive: true,
        generatedCount: 1, // the source invoice is the first in the series
        nextGenerationDate: computeNextGenerationDate(dayOfMonth, source.dateOfIssue),
      })
      .returning();

    if (source.items.length > 0) {
      await tx.insert(recurringInvoiceItems).values(
        source.items.map((item) => ({
          recurringInvoiceId: row.id,
          description: item.description,
          quantity: item.quantity,
          unitPrice: item.unitPrice,
          amount: item.amount,
          sortOrder: item.sortOrder,
        })),
      );
    }

    await tx
      .update(invoices)
      .set({ recurringInvoiceId: row.id, isAutoGenerated: false, updatedAt: new Date() })
      .where(eq(invoices.id, invoiceId));
    return row;
  });

  // If the first run date is already here (back-dated source), generate now.
  await runDueRecurring({ templateId: row.id });

  revalidatePath("/recurring");
  revalidatePath(`/invoices/${invoiceId}`);
  return row;
}

/**
 * Turn a saved payslip into a monthly recurring template. Earnings,
 * deductions, payment mode and signatory are copied; the gap between the pay
 * period and the payment date is kept (e.g. "pay October's salary on 5 Nov").
 */
export async function makePayslipRecurring(payslipId: string, dayOfMonth: number) {
  await requireSession();
  z.string().uuid().parse(payslipId);
  DayOfMonth.parse(dayOfMonth);

  const source = await db.query.payslips.findFirst({
    where: (p, { eq }) => eq(p.id, payslipId),
    with: { items: { orderBy: (it, { asc }) => asc(it.sortOrder) } },
  });
  if (!source) throw new Error("Payslip not found");
  if (!source.employeeId) throw new Error("Payslip has no employee");
  if (source.recurringPayslipId) throw new Error("This payslip is already part of a recurring schedule");

  const paid = parseDateString(source.paymentDate);
  const offset =
    (paid.getFullYear() - source.payPeriodYear) * 12 + (paid.getMonth() + 1 - source.payPeriodMonth);

  const row = await db.transaction(async (tx) => {
    const [row] = await tx
      .insert(recurringPayslips)
      .values({
        employeeId: source.employeeId!,
        currency: source.currency,
        paymentMode: source.paymentMode,
        notes: source.notes,
        authorizedByName: source.authorizedByName,
        authorizedByTitle: source.authorizedByTitle,
        periodOffsetMonths: Math.min(12, Math.max(0, offset)),
        dayOfMonth,
        isActive: true,
        generatedCount: 1,
        nextGenerationDate: computeNextGenerationDate(dayOfMonth, source.paymentDate),
      })
      .returning();

    if (source.items.length > 0) {
      await tx.insert(recurringPayslipItems).values(
        source.items.map((item) => ({
          recurringPayslipId: row.id,
          description: item.description,
          type: item.type,
          amount: item.amount,
          sortOrder: item.sortOrder,
        })),
      );
    }

    await tx
      .update(payslips)
      .set({ recurringPayslipId: row.id, isAutoGenerated: false, updatedAt: new Date() })
      .where(eq(payslips.id, payslipId));
    return row;
  });

  await runDueRecurring({ templateId: row.id });

  revalidatePath("/recurring");
  revalidatePath(`/payslips/${payslipId}`);
  return row;
}

function tableFor(kind: RecurringKind) {
  return kind === "invoice" ? recurringInvoices : recurringPayslips;
}

export async function setRecurringActive(kind: RecurringKind, id: string, active: boolean) {
  await requireSession();
  Kind.parse(kind);
  const table = tableFor(kind);

  const [current] = await db.select().from(table).where(eq(table.id, id));
  if (!current) throw new Error("Recurring template not found");

  // Resuming a paused template must not back-fill the months it was paused
  // for — restart from the next upcoming run day instead.
  const nextGenerationDate =
    active && !current.isActive
      ? computeNextGenerationDate(current.dayOfMonth)
      : current.nextGenerationDate;

  await db
    .update(table)
    .set({ isActive: active, nextGenerationDate, updatedAt: new Date() })
    .where(eq(table.id, id));

  revalidatePath("/recurring");
}

export async function setRecurringDayOfMonth(kind: RecurringKind, id: string, dayOfMonth: number) {
  await requireSession();
  Kind.parse(kind);
  DayOfMonth.parse(dayOfMonth);
  const table = tableFor(kind);

  const [current] = await db.select().from(table).where(eq(table.id, id));
  if (!current) throw new Error("Recurring template not found");

  // Keep the month of the pending run, move only the day — but never into the past.
  const pending = parseDateString(current.nextGenerationDate);
  const movedStr = toDateString(new Date(pending.getFullYear(), pending.getMonth(), dayOfMonth));
  const upcoming = computeNextGenerationDate(dayOfMonth);
  const nextGenerationDate = movedStr >= upcoming ? movedStr : upcoming;

  await db
    .update(table)
    .set({ dayOfMonth, nextGenerationDate, updatedAt: new Date() })
    .where(eq(table.id, id));

  revalidatePath("/recurring");
}

export async function deleteRecurringTemplate(kind: RecurringKind, id: string) {
  await requireSession();
  Kind.parse(kind);
  const table = tableFor(kind);
  // Generated documents keep existing; their template link is set to null.
  await db.delete(table).where(eq(table.id, id));
  revalidatePath("/recurring");
}

/** Generate everything that's due right now (also runs hourly in the background). */
export async function runRecurringNow() {
  await requireSession();
  const result = await runDueRecurring();
  revalidatePath("/recurring");
  revalidatePath("/invoices");
  revalidatePath("/payslips");
  return {
    invoices: result.invoices.length,
    payslips: result.payslips.length,
    skipped: result.skipped.map((s) => s.reason),
    errors: result.errors.map((e) => e.message),
  };
}
